"""Score a frozen replay panel with a recurrent CNN; no fitting or GPU use.

Reconstruct every delivered observation from the start. Compare native actor
features with a tracker fed only observations and past own moves. Replay truth
labels candidates separately; it is never a model input. Reports describe
choices on recorded histories, not trajectories generated by this policy.
"""
import argparse
from collections import Counter
from datetime import datetime, timezone
import gzip
import hashlib
import json
from pathlib import Path
import sys
import time

import numpy as np
import torch

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def check(ok, message):
    if not ok:
        raise ValueError(message)


def metrics(policy, risk, fatal, moves):
    """One decision, averaged across its legal candidates; higher risk = danger."""
    policy, risk = np.asarray(policy, np.float64), np.asarray(risk, np.float64)
    y = np.asarray(fatal, np.float64)
    check(len(moves) > 0 and len(policy) == len(risk) == len(y) == len(moves), 'candidate lengths')
    check(np.isfinite(policy).all() and np.isfinite(risk).all(), 'nonfinite model output')
    check(np.isin(y, [0., 1.]).all(), 'nonbinary labels')
    prob = np.exp(-np.logaddexp(0, -risk))
    pp = np.exp(policy - policy.max()); pp /= pp.sum()
    safe, bad = risk[y == 0], risk[y == 1]
    auc = None
    if len(safe) and len(bad):
        # Exact pairwise ordering; no O(M^2) temporary matrix.
        sorted_safe = np.sort(safe)
        lower = np.searchsorted(sorted_safe, bad, side='left')
        upper = np.searchsorted(sorted_safe, bad, side='right')
        auc = float((lower + .5 * (upper - lower)).sum() / (len(safe) * len(bad)))
    top = min(range(len(moves)), key=lambda i: (-policy[i], moves[i]))
    low = min(range(len(moves)), key=lambda i: (risk[i], -policy[i], moves[i]))
    return {'log_loss': float(np.mean(np.logaddexp(0, risk) - y * risk)),
            'brier': float(np.mean((prob - y) ** 2)), 'auc': auc,
            'policy_fatal': int(y[top]), 'min_risk_fatal': int(y[low]),
            'policy_fatal_mass': float(pp @ y), 'safe_available': bool(len(safe)),
            'mixed': bool(len(safe) and len(bad)),
            'policy_move': moves[top], 'min_risk_move': moves[low]}


def aggregate(rows):
    check(bool(rows), 'empty decision set')
    out = {'decisions': len(rows)}
    for key in ('log_loss', 'brier', 'policy_fatal', 'min_risk_fatal', 'policy_fatal_mass'):
        out[key] = float(np.mean([r[key] for r in rows]))
    aucs = [r['auc'] for r in rows if r['auc'] is not None]
    out.update(mixed_decisions=len(aucs), auc=None if not aucs else float(np.mean(aucs)),
               policy_fatal_count=sum(r['policy_fatal'] for r in rows),
               min_risk_fatal_count=sum(r['min_risk_fatal'] for r in rows),
               no_escape_decisions=sum(not r['safe_available'] for r in rows),
               avoidable_policy_fatal_count=sum(r['policy_fatal'] for r in rows if r['safe_available']),
               avoidable_min_risk_fatal_count=sum(r['min_risk_fatal'] for r in rows if r['safe_available']))
    return out


def prepare_game(case, env, referee, features, decode_action, deadline):
    path = ROOT / case['replay']
    check(sha(path) == case['replay_sha256'], 'replay changed')
    replay = json.loads(path.read_bytes()); frames = replay['frames']
    side = 0 if case['side'] == 'white' else 1
    tracker = features.FeatureTracker(side)
    board = referee.FowBoard(); repetitions = Counter({referee.position_key(board): 1})
    env.reset(0); planes, scalars, decisions = [], [], {}
    max_feature_error = 0.
    for ply, frame in enumerate(frames[:-1]):
        check(time.monotonic() < deadline, 'wall cap reached')
        check(env.status(0) == 0 and referee.outcome(board, repetitions) is None, 'early termination')
        check(env.board(0) == frame['board'], 'native board mismatch')
        mover = ply % 2
        check(env.side_to_move(0) == mover, 'side mismatch')
        phase = 0 if ply == 0 else 1 if (ply - 1) % 2 == side else 2
        tracker.observe(frame[case['side']], phase, ply)
        actor_planes, actor_scalars = tracker.planes(), tracker.scalars()
        native_planes, native_scalars = env.take_events(0, side)
        env.take_events(0, 1 - side)
        check(len(native_planes) == 1, 'missing or duplicate observation event')
        delta = max(float(np.max(np.abs(actor_planes - native_planes[0]))),
                    float(np.max(np.abs(actor_scalars - native_scalars[0]))))
        check(delta <= 1e-7, 'native/observation-only feature mismatch')
        max_feature_error = max(max_feature_error, delta)
        planes.append(actor_planes); scalars.append(actor_scalars)
        f, t, promotion = env.candidates(0)
        moves = [decode_action((int(a) * 64 + int(b)) * 5 + int(c), mover)
                 for a, b, c in zip(f, t, promotion)]
        check(len(set(moves)) == len(moves), 'duplicate candidates')
        if mover == side:
            check(set(moves) == set(tracker.legal_candidates()), 'actor candidate mismatch')
            check(set(moves) == {m.uci() for m in board.generate_pseudo_legal_moves()}, 'referee candidate mismatch')
            labels = env.danger(0)
            check(len(labels) == len(moves), 'label length mismatch')
            for uci, label in zip(moves, labels):
                after = board.copy(stack=False); after.push(after.parse_uci(uci))
                king = after.king(board.turn)
                fatal = king is None or after.is_attacked_by(after.turn, king)
                check(int(label) == int(fatal), 'native/referee danger mismatch')
            king = board.king(board.turn)
            attackers = [] if king is None else list(board.attackers(not board.turn, king))
            visible_attackers = [sq for sq in attackers if frame[case['side']][sq] != '?']
            context = 'no_current_attack' if not attackers else 'visible_attack' if visible_attackers else 'hidden_attack'
            decisions[ply] = {'moves': moves, 'candidate_arrays': (f, t, promotion),
                              'fatal': labels.tolist(), 'attack_context': context,
                              'recorded_move': frames[ply + 1]['move']}
        # Apply the recorded move only AFTER constructing this frame's inputs.
        move = frames[ply + 1]['move']
        if mover == side:
            tracker.record_own_move(move)
        env.step_all(np.array([moves.index(move)], dtype=np.int32))
        board.push(board.parse_uci(move)); repetitions[referee.position_key(board)] += 1
    check(sorted(decisions) == case['decision_frames'], 'frozen decision coverage changed')
    check(env.board(0) == frames[-1]['board'], 'terminal board mismatch')
    check(referee.outcome(board, repetitions) == (replay['result'], replay['reason']), 'terminal outcome mismatch')
    check(env.status(0) == {'1-0': 1, '0-1': 2, '1/2-1/2': 3}[replay['result']], 'native outcome mismatch')
    x, s = np.stack(planes), np.stack(scalars)
    digest = hashlib.sha256(x.tobytes() + s.tobytes())
    digest.update(json.dumps({k: d['moves'] for k, d in decisions.items()}, sort_keys=True).encode())
    return {'case': case, 'planes': x, 'scalars': s, 'decisions': decisions,
            'actor_input_sha256': digest.hexdigest(), 'feature_error': max_feature_error}


@torch.inference_mode()
def score_games(model, games, deadline):
    hidden = model.initial_hidden(len(games), 'cpu')
    output = [[] for _ in games]
    for event in range(max(len(g['planes']) for g in games)):
        check(time.monotonic() < deadline, 'wall cap reached')
        active = [i for i, g in enumerate(games) if event < len(g['planes'])]
        x = torch.from_numpy(np.stack([games[i]['planes'][event] for i in active]))
        s = torch.from_numpy(np.stack([games[i]['scalars'][event] for i in active]))
        h, spatial, _, _ = model.observe(x, s, hidden[active])
        hidden[active] = h
        selected = [j for j, i in enumerate(active) if event in games[i]['decisions']]
        if not selected:
            continue
        ids = [active[j] for j in selected]
        records = [games[i]['decisions'][event] for i in ids]
        width = max(len(r['moves']) for r in records)
        arrays = [torch.zeros(len(ids), width, dtype=torch.long) for _ in range(3)]
        for j, record in enumerate(records):
            for k, source in enumerate(record['candidate_arrays']):
                arrays[k][j, :len(source)] = torch.from_numpy(source.astype(np.int64))
        policy, risk = model.score(h[selected], spatial[selected], *arrays)
        for j, i in enumerate(ids):
            record = records[j]; n = len(record['moves'])
            p, z = policy[j, :n].numpy().tolist(), risk[j, :n].numpy().tolist()
            output[i].append({'frame': event, 'moves': record['moves'], 'fatal': record['fatal'],
                              'policy_logits': p, 'risk_logits': z,
                              'attack_context': record['attack_context'],
                              'recorded_move': record['recorded_move'],
                              'recorded_fatal': record['fatal'][record['moves'].index(record['recorded_move'])],
                              'metrics': metrics(p, z, record['fatal'], record['moves'])})
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', type=Path)
    parser.add_argument('--expected-checkpoint-sha256')
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--referee-dir', type=Path, default=Path('/home/henrytan/git/fow-starter'))
    parser.add_argument('--limit', type=int, default=0, help='first N frozen games for a correctness pilot only')
    parser.add_argument('--batch-games', type=int, default=8)
    parser.add_argument('--wall-cap', type=float, default=900)
    args = parser.parse_args()
    check(args.batch_games > 0 and args.limit >= 0, 'invalid limit/batch')
    check(not args.output_dir.exists(), 'use a fresh output directory')
    args.output_dir.mkdir(parents=True)
    start = time.monotonic(); deadline = start + args.wall_cap
    torch.set_num_threads(2)
    receipt = json.loads((HERE / 'risk-run-preflight/preflight.json').read_bytes())
    source = Path(receipt['source_root'])
    for name, digest in receipt['source_sha256'].items():
        check(sha(source / name) == digest, 'prepared source changed: ' + name)
    panel_path = HERE / 'risk-run-preflight/validation-games.json'
    check(sha(panel_path) == receipt['validation_sha256'], 'validation manifest changed')
    panel = json.loads(panel_path.read_bytes())
    check(sha(args.referee_dir / 'referee.py') == panel['referee_sha256'], 'referee changed')
    initial = receipt['actor_checkpoints']['initial_actor_and_reference']
    checkpoint = args.checkpoint or Path(initial['path'])
    expected = args.expected_checkpoint_sha256 if args.checkpoint else initial['sha256']
    check(bool(expected) and sha(checkpoint) == expected, 'checkpoint hash missing or changed')
    sys.path.insert(0, str(source))
    from learning.pretrain import load_model
    from learning import features, _native
    from learning.batch_env import BatchEnv
    from learning.action_codec import decode_action
    sys.path.insert(0, str(args.referee_dir))
    import referee
    model, payload = load_model(checkpoint, 'cpu'); model.eval()
    check(payload['feature_version'] == 'features-v2' and payload['action_version'] == 'actions-v1', 'model schema mismatch')
    cases = panel['games'][:args.limit] if args.limit else panel['games']
    env = BatchEnv(1, max_plies=10000)
    summaries, all_metrics, failures = [], [], []
    strata = {}; recorded_fatal = 0; candidate_labels = 0
    timings = {'prepare_seconds': 0., 'inference_seconds': 0.}
    raw_path = args.output_dir / 'predictions.jsonl.gz'
    with gzip.open(raw_path, 'wt') as raw:
        try:
            for begin in range(0, len(cases), args.batch_games):
                now = time.monotonic()
                games = [prepare_game(c, env, referee, features, decode_action, deadline)
                         for c in cases[begin:begin + args.batch_games]]
                timings['prepare_seconds'] += time.monotonic() - now
                now = time.monotonic(); predictions = score_games(model, games, deadline)
                timings['inference_seconds'] += time.monotonic() - now
                for game, rows in zip(games, predictions):
                    case = game['case']; check(len(rows) == len(case['decision_frames']), 'prediction coverage mismatch')
                    mm = [r['metrics'] for r in rows]; all_metrics.extend(mm)
                    record = {'game': case['game'], 'side': case['side'], 'opponent': case['opponent'],
                              'replay_sha256': case['replay_sha256'], 'actor_input_sha256': game['actor_input_sha256'],
                              'feature_parity_max_error': game['feature_error'], 'metrics': aggregate(mm)}
                    summaries.append(record)
                    for row in rows:
                        strata.setdefault(row['attack_context'], []).append(row['metrics'])
                        recorded_fatal += row['recorded_fatal']; candidate_labels += len(row['moves'])
                    raw.write(json.dumps({**record, 'decisions': rows}, separators=(',', ':')) + '\n')
                print(f'evaluated {len(summaries)}/{len(cases)} games; no fitting', file=sys.stderr, flush=True)
        except (ValueError, RuntimeError) as error:
            failures.append(str(error))
    state = 'complete' if not failures and len(summaries) == len(cases) else 'failed'
    summary = {'state': state, 'classification': 'frozen-history CPU model evaluation; no policy-generated matches or fitting',
               'completed_at': datetime.now(timezone.utc).isoformat(),
               'collector_sha256': sha(Path(__file__)), 'panel_sha256': sha(panel_path),
               'checkpoint': str(checkpoint), 'checkpoint_sha256': sha(checkpoint),
               'architecture': model.architecture, 'native_library_sha256': sha(_native.LIBRARY),
               'source_receipt_sha256': sha(HERE / 'risk-run-preflight/preflight.json'),
               'predictions_sha256': sha(raw_path), 'predictions_file': str(raw_path),
               'games_requested': len(cases), 'games_completed': len(summaries), 'full_panel': len(cases) == len(panel['games']),
               'game_records': summaries, 'summary': aggregate(all_metrics) if all_metrics else None,
               'attack_context_metrics': {k: aggregate(v) for k, v in strata.items()},
               'recorded_v35_fatal_choices': recorded_fatal, 'candidate_labels_verified': candidate_labels,
               'timings': {**timings, 'wall_seconds': time.monotonic() - start},
               'batch_games': args.batch_games, 'wall_cap_seconds': args.wall_cap, 'gpu_used': False,
               'failures': failures,
               'limits': ['One-step predictions on v35 replay histories; these are not model-generated game outcomes.',
                          'Truth supplies labels only. Actor features/candidates are verified against observation-only reconstruction.',
                          'Game-wise means are the units for the paired comparison; summary metrics here average decisions.',
                          'Complete decision logs are retained for paired rescues/regressions and alternative aggregation.']}
    (args.output_dir / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps({k: summary[k] for k in ('state', 'games_completed', 'summary', 'timings', 'failures')}))
    return 0 if state == 'complete' else 1


if __name__ == '__main__':
    raise SystemExit(main())
