"""Fit the 20-ply opponent classifier on all samples and write classifier_weights.h plus parity vectors."""
import json, os, sys, numpy as np, torch
torch.set_num_threads(1)
here = os.path.dirname(os.path.abspath(__file__)); wt = sys.argv[1]
d = np.load(os.path.join(here, "dataset.npz")); X = d["X20"]; y = d["y"]; classes = [str(c) for c in d["classes"]]
mu, sd = X.mean(0), X.std(0) + 1e-4
Xt = torch.tensor((X - mu) / sd); yt = torch.tensor(y)
W = torch.zeros(X.shape[1], len(classes), requires_grad=True); b = torch.zeros(len(classes), requires_grad=True)
opt = torch.optim.LBFGS([W, b], max_iter=300, line_search_fn="strong_wolfe")
def closure():
    opt.zero_grad(); loss = torch.nn.functional.cross_entropy(Xt @ W + b, yt) + 1e-3 * (W ** 2).sum(); loss.backward(); return loss
opt.step(closure)
W = W.detach().numpy(); b = b.detach().numpy()
GROUP = {"TA Baseline P": 0, "TA Baseline A": 0, "TA Baseline S": 1, "Greek Gift": 2, "Knight Vision": 2, "Decent Chess Bot": 2,
         "Strongly Invisible": 2, "duck": 2, "Instructors": 2, "Mist Opportunities": 3, "Apricot Squad": 4, "baseline.py": 4}
fmt = lambda a: ",".join(f"{v:.7g}" for v in a)
lines = ["// Generated by the opponent-classifier export (v26); do not edit by hand.",
         "// Multinomial logistic regression over a side's own views of plies 0..20:",
         "// visible enemy pieces by type (p,n,b,r,q,k) and square, averaged over the 21",
         "// views, then mean visible share, own pieces lost /16, and playing White.",
         f"// Classes: {', '.join(classes)}.",
         "// Held-out (by game, before this all-data refit): 12-way accuracy 44%, from our",
         "// own side 49%; TA Baselines P/A vs the rest AUC 0.94, top six vs the rest 0.89.",
         "#ifndef FOW_CLASSIFIER_WEIGHTS_H_", "#define FOW_CLASSIFIER_WEIGHTS_H_", "", "namespace fow {", "",
         f"inline constexpr int kClassifierFeatures = {X.shape[1]};", f"inline constexpr int kClassifierClasses = {len(classes)};",
         "inline constexpr int kClassifierViews = 21;",
         f"inline constexpr double kClassifierMean[kClassifierFeatures] = {{{fmt(mu)}}};",
         f"inline constexpr double kClassifierScale[kClassifierFeatures] = {{{fmt(sd)}}};",
         f"inline constexpr double kClassifierBias[kClassifierClasses] = {{{fmt(b)}}};",
         f"// Row-major [feature][class].",
         f"inline constexpr double kClassifierWeights[kClassifierFeatures * kClassifierClasses] = {{{fmt(W.ravel())}}};",
         "// Opponent group of each class: 0 TA Baselines P/A, 1 TA Baseline S, 2 top six, 3 Mist, 4 others.",
         f"inline constexpr int kClassifierGroup[kClassifierClasses] = {{{','.join(str(GROUP[c]) for c in classes)}}};",
         "", "}  // namespace fow", "", "#endif  // FOW_CLASSIFIER_WEIGHTS_H_", ""]
open(os.path.join(wt, "classifier_weights.h"), "w").write("\n".join(lines))
# parity vectors: the first 21 views of a few games from both sides, with the expected group posterior
sys.path.insert(0, here); from build import feats
import glob
games = sorted(glob.glob(os.path.expanduser("~/git/iamavirus/data/raw/games/*/replay.json")))[:6]
with open(os.path.join(wt, "tests", "classifier_vectors.txt"), "w") as f:
    for p in games:
        F = json.load(open(p))["frames"]
        if len(F) < 21: continue
        for colour in ("white", "black"):
            x = (feats(F, colour, 20) - mu) / sd; z = x @ W + b; z = np.exp(z - z.max()); z /= z.sum()
            g = np.zeros(5)
            for i, c in enumerate(classes): g[GROUP[c]] += z[i]
            f.write(colour + " " + " ".join(F[t][colour] for t in range(21)) + " " + " ".join(f"{v:.8f}" for v in g) + "\n")
print("wrote classifier_weights.h", W.shape, "and parity vectors")
